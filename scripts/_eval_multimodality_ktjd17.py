"""MultiModality (MModality) for the frozen text-to-motion protocol.

The metric AniMo (CVPR 2025) reports beside Diversity and the one number the retrieval report cannot yield: R-Precision,
FID, MM-Dist and Diversity all read ONE sample per caption, while MultiModality asks how far apart the samples a SINGLE
caption produces are. So it needs its own generation, and this script only SCORES it: the repeats are generated by the
canonical scripts/_eval_v2_gen_in_evalspace.py --save_gen (same 20 Euler steps, same cfg 2.0, same plan, same rig
sharding), one saved shard per sampling seed, and every shard's own metadata is what binds them together here.

Definition -- a VERBATIM port of the reference (outside_docs/MotionMillion-Codes/utils/eval_trans.py:1213,
calculate_multimodality, called with multimodality_times=10 at line 1152 over activation[N_texts, R=30, D]):
  pick `mm_times` repeat-indices twice, without replacement, ONE pick shared by every caption; take the L2 between the
  two picks per caption; average over captions and picks.

Two properties of that reference are load-bearing and are enforced, not assumed:
  * R must comfortably exceed mm_times. The two index lists are drawn independently, so a fraction ~1/R of the pairs is
    a sample against ITSELF (distance 0) and biases MultiModality DOWN; at the reference's R=30 that is ~3%, at R=11 it
    would be ~9%. Measured, that fraction is exactly 1/R, so R is part of the DEFINITION and --mm_repeats is
    enforced exactly, never as a minimum.
  * the repeats must be the same captions in the same order, or the metric averages distances between unrelated
    motions. The row order of every repeat is digested and must match exactly.

The repeats are bound to the run that was REQUESTED, not to whatever the shell glob expanded to: --manifest is
written by scripts/_mm_gen_queue.sh only when every requested seed finished, and its seed list, rig shard and
checkpoint digest must match the files exactly. --bind_report ties the evaluator and the checkpoint to the ones the
published table scored with.

usage:
  python scripts/_eval_multimodality_ktjd17.py --gen_ckpt CKPT --reps DIR/rep_seed*.npz \\
      --manifest DIR/manifest.json --bind_report REPORT_strict.json --out OUT.json
"""
from __future__ import annotations
import argparse, hashlib, io, json, sys
from pathlib import Path
import numpy as np
import torch
from scipy import linalg

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from scripts._eval_v2_gen_in_evalspace import (LEGACY_SOURCE_FINGERPRINTS, PROTOCOL_VAL_N,      # noqa: E402
                                               encode_split, load_evaluator, source_fingerprint)
from scripts._eval_controls_ktjd17 import EVAL_CKPT                                             # noqa: E402
from src.data.ktjd17_incontext import Ktjd17Base                                                # noqa: E402
from src.data.ktjd17_t2m_eval_dataset import Ktjd17T2MEvalDataset                               # noqa: E402

PROTOCOL_STEPS, PROTOCOL_CFG = 20, 2.0


def calculate_multimodality(activation: np.ndarray, multimodality_times: int, rng: np.random.RandomState) -> float:
    """VERBATIM from MotionMillion utils/eval_trans.py:1213, with the module-level np.random replaced by an explicit
    RandomState so a draw is reproducible and can be repeated."""
    assert len(activation.shape) == 3
    assert activation.shape[1] > multimodality_times
    num_per_sent = activation.shape[1]
    first_dices = rng.choice(num_per_sent, multimodality_times, replace=False)
    second_dices = rng.choice(num_per_sent, multimodality_times, replace=False)
    dist = linalg.norm(activation[:, first_dices] - activation[:, second_dices], axis=2)
    return dist.mean()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen_ckpt", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--reps", nargs="+", required=True, help="one --save_gen shard per sampling seed, same rig shard")
    ap.add_argument("--eval_ckpt", default=EVAL_CKPT)
    ap.add_argument("--manifest", required=True,
                    help="the generating pass's manifest.json. scripts/_mm_gen_queue.sh writes it ONLY when every "
                         "requested repeat finished, so it is what makes a partial pass unscoreable: a glob of .npz "
                         "cannot say how many repeats were asked for, or of which rig shard (codex divmm r1 P1-1)")
    ap.add_argument("--bind_report", required=True,
                    help="a strict gen-eval report of THIS checkpoint. Binds the evaluator and the checkpoint to the "
                         "ones the published table used, which the repeats themselves do not record")
    ap.add_argument("--mm_times", type=int, default=10, help="index picks per side (reference: 10)")
    ap.add_argument("--mm_repeats", type=int, default=30,
                    help="required number of repeats, EXACTLY (reference: 30). R is part of the metric's definition, "
                         "not a budget: ~1/R of the pairs is a sample against itself, so a different R is a "
                         "different number")
    ap.add_argument("--n_draws", type=int, default=20,
                    help="index draws averaged over. This is Monte-Carlo error of the index pick on a FIXED sample "
                         "pool, NOT independent evaluation replications: more draws shrink it without generating "
                         "any new motion (codex divmm r1 P2-6)")
    ap.add_argument("--seed", type=int, default=42, help="RNG for the index draws (NOT a sampling seed)")
    ap.add_argument("--encode_batch", type=int, default=64)
    a = ap.parse_args()
    if a.mm_times < 1:
        raise SystemExit(f"[refuse] --mm_times {a.mm_times}: an empty pick makes MultiModality an empty mean")
    if a.n_draws < 1:
        raise SystemExit(f"[refuse] --n_draws {a.n_draws} is not a usable number of draws")
    if len(a.reps) != a.mm_repeats:
        raise SystemExit(f"[refuse] {len(a.reps)} repeat files, --mm_repeats says {a.mm_repeats}: ~1/R of the pairs is "
                         f"a sample against itself, so a different R is a different metric, not a smaller sample")
    if len(a.reps) <= a.mm_times:
        raise SystemExit(f"[refuse] {len(a.reps)} repeats <= --mm_times {a.mm_times}: the reference asserts R > mm_times")
    if not torch.cuda.is_available():
        raise SystemExit("[refuse] no CUDA device: the samples were generated on a GPU and a CPU fallback is different arithmetic")
    dev = "cuda"

    man = json.loads(Path(a.manifest).read_text())
    if man.get("format") != "mm-repeat-manifest-v1":
        raise SystemExit(f"[refuse] {a.manifest} is format {man.get('format')!r}, expected mm-repeat-manifest-v1")
    want_seeds = man.get("seeds")
    if (not isinstance(want_seeds, list) or not want_seeds
            or any(type(x) is not int for x in want_seeds) or len(set(want_seeds)) != len(want_seeds)):
        raise SystemExit(f"[refuse] {a.manifest} does not list distinct integer seeds")
    if len(want_seeds) != a.mm_repeats:
        raise SystemExit(f"[refuse] the manifest requested {len(want_seeds)} repeats, --mm_repeats says {a.mm_repeats}")
    if int(man.get("steps", -1)) != PROTOCOL_STEPS or float(man.get("cfg_text", -1)) != PROTOCOL_CFG \
            or man.get("tf32") is not True:
        raise SystemExit(f"[refuse] the manifest describes steps={man.get('steps')} cfg={man.get('cfg_text')} "
                         f"tf32={man.get('tf32')}; this scores the frozen {PROTOCOL_STEPS}-step cfg-{PROTOCOL_CFG} "
                         f"sampler with TF32 on")
    if type(man.get("nshards")) is not int or type(man.get("shard")) is not int:
        raise SystemExit(f"[refuse] {a.manifest} does not pin an integer rig shard")

    buf = Path(a.gen_ckpt).read_bytes(); gen_sha = hashlib.sha256(buf).hexdigest()
    if str(man.get("gen_ckpt_sha256")) != gen_sha:
        raise SystemExit(f"[refuse] the manifest was written for checkpoint {str(man.get('gen_ckpt_sha256'))[:16]}, "
                         f"{a.gen_ckpt} hashes {gen_sha[:16]}")
    rp = json.loads(Path(a.bind_report).read_text())
    _rpp = rp.get("protocol")
    if not isinstance(_rpp, dict):
        raise SystemExit(f"[refuse] {a.bind_report} has no protocol block; it is not a gen-eval report")
    # a hand-made object carrying two matching hashes would otherwise satisfy this (codex divmm r2 P2): require the
    # marks only a real strict merge writes
    if _rpp.get("strict_acceptance") is not True:
        raise SystemExit(f"[refuse] {a.bind_report} is not a strict-acceptance report "
                         f"(strict_acceptance={_rpp.get('strict_acceptance')!r})")
    for _k in ("eval_order_sha256", "eval_ckpt_sha256"):
        if not str(_rpp.get(_k) or ""):
            raise SystemExit(f"[refuse] {a.bind_report} records no {_k} -- re-run its merge")
    if not str(((_rpp.get("generation") or {}).get("scoring_source_fingerprint")) or ""):
        raise SystemExit(f"[refuse] {a.bind_report} records no scoring_source_fingerprint -- re-run its merge")
    if str(_rpp.get("gen_ckpt_sha256")) != gen_sha:
        raise SystemExit(f"[refuse] {a.bind_report} scored a different checkpoint than {a.gen_ckpt}")
    ck = torch.load(io.BytesIO(buf), map_location="cpu", weights_only=False); del buf
    ca = ck["args"]; ca = vars(ca) if not isinstance(ca, dict) else ca
    root, excl = ca["ktjd_root"], (ca.get("exclude_clips") or None)
    # as in the diversity script: these samples go straight into the evaluator's encoder, which is only correct when
    # they already live in its per-cell KTJD-17 space. A derived view needs the merge's conversion.
    if (Path(root) / "derivation.json").is_file() or str(ca.get("rep_norm") or "percell") != "percell":
        raise SystemExit(f"[refuse] {a.gen_ckpt} serves normalisation {ca.get('rep_norm')!r} from {root}; this script "
                         f"scores the evaluator's per-cell KTJD-17 space directly and does not convert")
    base = Ktjd17Base(root, caption_emb_cache=ca["caption_cache"], joint_semantics=ca["joint_sem"],
                      texts_json=ca["texts_json"],
                      percell_stats=ca.get("ktjd_percell_stats", "data/ktjd17_percell_stats_v1.npz"),
                      exclude_clips=excl, normalization="percell")
    live = {**base.provenance, "exclusion": base.provenance_exclusion}
    drift = sorted(k for k, v in (ck.get("ktjd_pins") or {}).items() if k in live and live[k] != v)
    if drift:
        raise SystemExit(f"[refuse] data drift vs the checkpoint's ktjd_pins: {drift}")
    eval_ds = Ktjd17T2MEvalDataset(base, "val", max_frames=240, exclude=excl)
    if len(eval_ds) != PROTOCOL_VAL_N:
        raise SystemExit(f"[refuse] eval val has {len(eval_ds)} clips, protocol pins {PROTOCOL_VAL_N}")

    # ---------------- load the repeats; they must be ONE protocol differing ONLY in the sampling seed ----------------
    reps, shared, seeds, rep_meta = [], None, [], []
    for p in sorted(a.reps):
        blob = Path(p).read_bytes(); fsha = hashlib.sha256(blob).hexdigest()
        z = np.load(io.BytesIO(blob), allow_pickle=False); m = json.loads(str(z["__meta"])); del blob
        if str(m.get("gen_ckpt_sha256")) != gen_sha:
            raise SystemExit(f"[refuse] repeat {p} is not from this checkpoint")
        # protocol_variant is deliberately NOT in this key: the canonical script stamps "seed" for every seed except
        # 42, which it refuses to stamp, so requiring equality would make a set containing 42 unscoreable. It is
        # checked per repeat instead, just below (codex divmm r2 P2).
        key = {k: m.get(k) for k in ("steps", "cfg_text", "nshards", "shard", "plan_sha256", "shard_clips_sha256",
                                     "gen_batch", "base_provenance_sha256", "exclude_clips",
                                     "source_fingerprint", "cohort")}
        key["runtime"] = m.get("runtime")
        if shared is None:
            shared = key
        elif key != shared:
            raise SystemExit(f"[refuse] repeat {p} does not share the first repeat's protocol: "
                             f"{ {k: (v, shared.get(k)) for k, v in key.items() if v != shared.get(k)} }")
        want_var = None if m.get("seed") == 42 else "seed"
        if m.get("protocol_variant") != want_var:
            raise SystemExit(f"[refuse] repeat {p} is seed {m.get('seed')} but stamped protocol_variant="
                             f"{m.get('protocol_variant')!r}; the canonical script stamps {want_var!r} for that seed")
        seeds.append(m.get("seed"))
        g = {k[6:]: np.asarray(z[k], dtype=np.float32) for k in z.files if k.startswith("clip__")}
        if not g:
            raise SystemExit(f"[refuse] repeat {p} holds no samples")
        reps.append(g)
        rep_meta.append({"path": p, "sha256": fsha, "seed": m.get("seed"), "device": m.get("device"),
                         "n_clips": len(g)})
        print(f"[mm] loaded {p} seed={m.get('seed')} clips={len(g)} sha={fsha[:12]}", flush=True)
    # DIFFERENT NOISE is the whole measurement: repeated seeds would be the same sample counted twice and would drag
    # MultiModality toward 0 without any of the identity checks noticing.
    if len(set(seeds)) != len(seeds):
        dup = sorted({s for s in seeds if seeds.count(s) > 1})
        raise SystemExit(f"[refuse] sampling seeds repeat across the repeats {dup}: those are the same samples, not "
                         f"independent draws from one caption")
    if any(type(s) is not int for s in seeds):
        raise SystemExit(f"[refuse] a repeat records a non-integer sampling seed: {seeds}")
    if sorted(seeds) != sorted(want_seeds):
        raise SystemExit(f"[refuse] the repeats carry seeds {sorted(seeds)}, the manifest requested "
                         f"{sorted(want_seeds)}: a stale or unrequested file would otherwise pass as the run")
    if int(shared["nshards"]) != man["nshards"] or int(shared["shard"]) != man["shard"]:
        raise SystemExit(f"[refuse] the repeats are rig shard {shared['shard']}/{shared['nshards']}, the manifest "
                         f"pins {man['shard']}/{man['nshards']}: that is a different caption subset")
    # Two repeats holding the SAME bytes are one sample counted twice, and MultiModality would be dragged toward 0.
    # The digest sees equal float32 payloads; it CANNOT see why they are equal -- a duplicated file and a sampler that
    # ignores its noise look identical here, and the second would be a real finding of MultiModality 0. So this is a
    # conservative refusal on ambiguous provenance, not a claim about the model (codex divmm r1 P2-7, r2 P2).
    dig = [hashlib.sha256(b"".join(g[k].tobytes() for k in sorted(g))).hexdigest() for g in reps]
    if len(set(dig)) != len(dig):
        same = sorted({rep_meta[i]["path"] for i in range(len(dig)) for j in range(i + 1, len(dig)) if dig[i] == dig[j]}
                      | {rep_meta[j]["path"] for i in range(len(dig)) for j in range(i + 1, len(dig)) if dig[i] == dig[j]})
        raise SystemExit(f"[refuse] two repeats hold byte-identical samples under different seeds: {same}. Either the "
                         f"same file was supplied twice / copied, or the sampler ignored its noise. Establish which "
                         f"before scoring -- this script cannot tell them apart.")
    if shared["steps"] != PROTOCOL_STEPS or float(shared["cfg_text"]) != PROTOCOL_CFG:
        raise SystemExit(f"[refuse] the repeats were sampled at steps={shared['steps']} cfg={shared['cfg_text']}; "
                         f"the frozen protocol is {PROTOCOL_STEPS} steps at cfg {PROTOCOL_CFG}")
    clip_sets = {frozenset(g) for g in reps}
    if len(clip_sets) != 1:
        raise SystemExit(f"[refuse] the repeats do not cover the same captions "
                         f"({sorted(len(c) for c in clip_sets)} distinct clip sets)")
    keep = set(next(iter(clip_sets)))
    # the code that produced the samples: live, or a state the registry has audited as producing the same samples
    live_fp = source_fingerprint(ca.get("anchor", "none"), flat=bool(ca.get("flat_joints", 0)))
    rep_fp = str(shared["source_fingerprint"] or "")
    if rep_fp != live_fp and rep_fp not in LEGACY_SOURCE_FINGERPRINTS:
        raise SystemExit(f"[refuse] the repeats were generated by {rep_fp[:16]}, live is {live_fp[:16]} and it is not "
                         f"an audited legacy fingerprint")
    for k in ("allow_tf32_matmul", "allow_tf32_cudnn", "float32_matmul_precision"):
        if k not in (shared["runtime"] or {}):
            raise SystemExit(f"[refuse] the repeats record no {k}; the scoring arithmetic cannot be matched to theirs")
    rt = shared["runtime"]
    # The manifest ASSERTS tf32; the shards RECORD it. Without this the two could disagree and the repeats would have
    # been sampled under arithmetic nobody asked for (codex divmm r2 P1).
    if type(rt.get("allow_tf32_matmul")) is not bool or rt["allow_tf32_matmul"] is not man["tf32"]:
        raise SystemExit(f"[refuse] the manifest requested tf32={man['tf32']} but the repeats record "
                         f"allow_tf32_matmul={rt.get('allow_tf32_matmul')!r}")
    torch.backends.cuda.matmul.allow_tf32 = bool(rt["allow_tf32_matmul"])
    torch.backends.cudnn.allow_tf32 = bool(rt["allow_tf32_cudnn"])
    torch.set_float32_matmul_precision(str(rt["float32_matmul_precision"]))

    core, eval_sha = load_evaluator(a.eval_ckpt, dev)
    if eval_sha != str(_rpp.get("eval_ckpt_sha256")):
        raise SystemExit(f"[refuse] evaluator {a.eval_ckpt} ({eval_sha[:16]}) is not the one {a.bind_report} used "
                         f"({str(rp['protocol'].get('eval_ckpt_sha256'))[:16]})")

    # ---------------- encode every repeat; row i must be the same caption in all of them ----------------
    embs, order_sha = [], None
    for i, g in enumerate(reps):
        _te, _gt, me_gen, meta = encode_split(core, eval_ds, g, dev, a, keep=keep)
        osha = hashlib.sha256("\n".join(str(m) for m in meta["motion_id"]).encode()).hexdigest()
        if order_sha is None:
            order_sha = osha
        elif osha != order_sha:
            raise SystemExit(f"[refuse] repeat {rep_meta[i]['path']} encodes a different caption order ({osha[:12]} vs "
                             f"{order_sha[:12]}): MultiModality would average distances between unrelated motions")
        embs.append(me_gen)
        print(f"[mm] encoded repeat {i + 1}/{len(reps)} seed={rep_meta[i]['seed']} rows={me_gen.shape[0]}", flush=True)
    act = torch.stack(embs, dim=1).numpy()          # [N_captions, R, D]
    if act.shape[0] != len(keep):
        raise SystemExit(f"[refuse] encoded {act.shape[0]} captions, the repeats hold {len(keep)}")
    print(f"[mm] activation {act.shape} (captions, repeats, dim)", flush=True)

    draws = [float(calculate_multimodality(act, a.mm_times, np.random.RandomState(a.seed + d)))
             for d in range(a.n_draws)]
    mm, sd = float(np.mean(draws)), float(np.std(draws))
    ci = 1.96 * sd / float(np.sqrt(len(draws)))
    out = {"gen_ckpt": a.gen_ckpt, "gen_ckpt_sha256": gen_sha, "eval_ckpt": a.eval_ckpt, "eval_ckpt_sha256": eval_sha,
           "metric": "multimodality", "n_captions": int(act.shape[0]), "n_repeats": int(act.shape[1]),
           "mm_times": a.mm_times, "n_draws": a.n_draws, "draw_seed": a.seed,
           "multimodality": mm, "std_over_draws": sd, "ci95_over_draws": ci,
           "multimodality_first_draw": draws[0], "draws": draws,
           "caption_order_sha256": order_sha, "sampling_seeds": sorted(seeds),
           "uncertainty_note": "std/ci95 over draws is MONTE-CARLO error of the index pick on a FIXED pool of "
                               "n_captions x n_repeats samples -- it is NOT the spread of independent evaluation "
                               "replications, and more draws shrink it without new generation",
           "manifest": a.manifest, "bind_report": a.bind_report,
           "scoring_runtime": {"torch": torch.__version__, "cuda": torch.version.cuda,
                               "cudnn": torch.backends.cudnn.version()},
           "embedding_space": "L2-normalised evaluator motion embedding (the evaluator normalises internally), "
                              "Euclidean distance -- bounded by 2, not on the scale of an unnormalised encoder",
           "protocol": {**{k: v for k, v in shared.items()}, "repeats": rep_meta,
                        "scoring_source_fingerprint_live": live_fp,
                        "legacy_fingerprint_note": LEGACY_SOURCE_FINGERPRINTS.get(rep_fp) if rep_fp != live_fp else None,
                        "scoring_device": torch.cuda.get_device_name(0)}}
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(out, indent=1))
    print(f"[mm] MultiModality {mm:.4f} +/- {ci:.4f} (Monte-Carlo error of {a.n_draws} index draws, fixed pool; "
          f"{out['n_captions']} captions x {out['n_repeats']} repeats, mm_times={a.mm_times})", flush=True)
    print(f"[mm] -> {a.out}", flush=True)


if __name__ == "__main__":
    main()
